def main():
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, default=Path("data/runtime/assistant.db"))
    parser.add_argument("--output", type=Path, default=Path("data/annotations"))
    args = parser.parse_args()
    connection = sqlite3.connect(args.database.resolve().as_uri() + "?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    course_id = "nlp-curriculum"
    version = connection.execute(
        "select graph_version from courses where id=?", (course_id,)
    ).fetchone()[0]
    nodes = []
    for row in connection.execute(
        "select id,name,aliases,description from knowledge_nodes "
        "where course_id=? and status='confirmed' and kind!='chapter' order by id",
        (course_id,),
    ):
        n = dict(row)
        n["aliases"] = json.loads(n["aliases"])
        nodes.append(n)
    connection.close()
    rows = []
    for index, line in enumerate(FAMILIES.strip().splitlines(), 1):
        labels, topic, *questions = line.split("|")
        ids = [] if labels == "-" else ["curriculum-" + code for code in labels.split(",")]
        for variant, question in enumerate(questions, 1):
            rows.append(
                {
                    "id": f"dev-{index:03}-{variant}",
                    "family_id": f"dev-family-{index:03}",
                    "question": question,
                    "node_ids": ids,
                    "label_status": "development",
                    "reviewer": "",
                    "source": "developer-authored",
                    "rationale": topic,
                }
            )
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "development-nlp-v1.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )
    (args.output / "curriculum-nodes-v1.json").write_text(
        json.dumps(
            {"course_id": course_id, "graph_version": version, "nodes": nodes},
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"开发数据：{len(rows)} 个问题，{index} 个家族，{len(nodes)} 个知识点；未经独立人工复核")


if __name__ == "__main__":
    main()
